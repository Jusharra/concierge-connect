import { writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Writes dist/_redirects. Static 301s live in netlify.toml; rows from Airtable
 * "Page Registry" (Status = Redirected) are added in Step 3.
 */
export const writeRedirects = (dist: string, extra: { from: string; to: string }[] = []) => {
  const lines = extra.map((r) => `${r.from}  ${r.to}  301!`);
  writeFileSync(join(dist, "_redirects"), `# generated by scripts/postbuild.ts\n${lines.join("\n")}\n`);
};

import { writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Writes dist/_redirects from Airtable "Page Registry" rows whose Status is "Redirected"
 * (data/redirects.json). The four known stale URLs are also pinned in netlify.toml as a safety net.
 */
export const writeRedirects = (dist: string, redirects: { from: string; to: string }[] = []) => {
  const lines = redirects.flatMap((r) => {
    const from = r.from.replace(/\/$/, "");
    return [`${from}  ${r.to}  301!`, `${from}/  ${r.to}  301!`];
  });
  writeFileSync(join(dist, "_redirects"), `# generated by scripts/postbuild.ts from Airtable Page Registry\n${lines.join("\n")}\n`);
};
